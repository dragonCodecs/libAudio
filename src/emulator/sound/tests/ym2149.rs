#[test]
fn tone_with_envelope()
{
	// Set up a PSG to generate 44.1kHz audio, and configure the channels and mixer settings
	let mut psg = YM2149::new(2_000_000, 44_100);
	// Make the test deterministic by forcing the edge states into a known state
	psg.force_channel_states(true);
	// Write channel configs, A = 638, B = 0, C = 0
	write_register(&mut psg, 0, 0x7e); // ChA fine
	write_register(&mut psg, 1, 0x02); // ChA rough
	write_register(&mut psg, 2, 0);
	write_register(&mut psg, 3, 0);
	write_register(&mut psg, 4, 0);
	write_register(&mut psg, 5, 0);
	// Noise freq = 0
	write_register(&mut psg, 6, 0);
	// Mixer config - enable only tone channel A
	write_register(&mut psg, 7, 0x3e);
	// Write channel level configs
	write_register(&mut psg, 8, 0x10);
	write_register(&mut psg, 9, 0);
	write_register(&mut psg, 10, 0);
	// And the envelope config, freq = 40, shape = 0xa
	write_register(&mut psg, 11, 0x28); // fine adjust
	write_register(&mut psg, 12, 0x00); // rough adjust
	write_register(&mut psg, 13, 0x0a); // shape

	assert!(!psg.sample_ready());
	// Having set everything up, run for enough cycles to generate a sample
	for cycle in 0..45 {
		assert!(psg.clock_cycle());
		if cycle == 44 {
			assert!(psg.sample_ready());
		} else {
			assert!(!psg.sample_ready());
		}
	}
	// Now check the value of the sample
	assert_eq!(psg.sample(), 0x2ad7);
	assert!(!psg.sample_ready());

	// Now run through generating the samples for the first bit of time on this config
	// and comparing them to the baked values above
	for sample in TONE_SAMPLES {
		while !psg.sample_ready() {
			assert!(psg.clock_cycle());
		}
		assert!(psg.sample_ready());
		assert_eq!(psg.sample(), sample.cast_signed());
		assert!(!psg.sample_ready());
	}
}
